                    <h3>General Information</h3>

                    Prepare your manuscript in Microsoft Word or export it from a different word processor into RTF
                    format,
                    following
                    the specifications that we show here.

                    For papers that deal with data analysis, make the data available to readers via a link you place in
                    your paper
                    to a
                    website where you store your data, if at all possible. We can help.

                    When you submit your paper for review, make sure that you have anonymized your paper by removing all
                    references
                    to
                    yourself or your institution. Make sure these are removed from the document properties as well. To
                    have your
                    paper
                    reviewed, you need first to submit a “blinded” version (without author or affiliation information)
                    that can be
                    blind
                    reviewed. After your paper is accepted, add the author information.

                    While there are no regulations on length, it will be exceptional for an article to exceed 20,000
                    words.

                    <h3>Language and Grammar Consistency</h3>

                    We publish papers written in English. If you have questions on English grammar or punctuation,
                    search the web
                    for
                    guidance. You can find an excellent guide at http://grammar.ccc.commnet.edu/grammar

                    While we prefer the use of U.S. spelling, we also accept other versions of English as long as they
                    are used
                    consistently throughout the paper.

                    <h3>Use of the singular “they”</h3>

                    When the gender of a person is unknown, the use of the singular “they” is accepted. Do not use
                    expressions such
                    as
                    “s/he” or “his or her.” For example, “Each student submitted their art portfolio to the committee”
                    is correct.
                    If
                    using the singular “they” as a generic third-person pronoun seems awkward, try rewording the
                    sentence or using
                    the
                    plural, such as “All students submitted their art portfolios to the committee” or “The art portfolio
                    of each
                    student
                    was submitted to the committee.” More information about this is at
                    https://apastyle.apa.org/blog/singular-they
                    and
                    https://apastyle.apa.org/style-grammar-guidelines/grammar/singular-they

                    <h3>Content</h3>

                    <h4>First Page Layout</h4>

                    To put the first page of your document in the proper format, copy the content of the first page from
