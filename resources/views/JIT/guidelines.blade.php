                    users or
                    their
                    institutions. Users are allowed to read, download, copy, distribute, print, search, or link to the
                    full texts of
                    the
                    articles or to use them for any other lawful purpose without asking prior permission from the
                    publisher or the
                    author. This is in accordance with the BOAI definition of open access.

                    Papers accepted for publication are published under a Creative Commons license and bear the
                    following notice:
                    (CC
                    BY-NC 4.0). This article is licensed to you under a Creative Commons Attribution-NonCommercial 4.0
                    International
                    License. Copyright is retained by the authors. We encourage readers to use, reuse, and build upon
                    the material
                    in
                    the Journal for non-commercial purposes as long as proper attribution is given when appropriate or
