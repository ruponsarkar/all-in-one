                    <h3>Format for Accepted Papers</h3>

                    Before your paper is accepted for publication, you will be required to submit an almost camera-ready
                    copy of
                    your
                    paper. The paper should be formatted according to the guidelines for accepted papers, using the ISI
                    Journal
                    Format
                    template. This document is an MS Word template that contains the Style Set for publications and the
                    instructions
                    for
                    applying these styles to your document. If you do not use MS Word, just print the document and
                    follow its
                    instructions.

                    Papers published in our journals follow the APA Guidelines, 7th edition and a summary of these
                    guidelines can be
                    found at http://help.informingscience.org/APA/

                    Because the contents of a paper may shift during formatting, make figures so they can be moved
                    and/or resized
                    easily. As explained in the detailed guidelines, this can best be done by saving a figure as an
                    image.

                    After the paper has been accepted, in addition to adding the name, affiliation, city, and country
                    for each
                    author at
                    the beginning of the paper, at the end of the paper in the Author section, add a brief paragraph or
                    two about
                    each
                    author. Please insert a head-and-shoulders photo of each author beside the biographical information.

                    Prior to final acceptance, the Editor will instruct the author to return a fully formatted paper for
                    final
                    review.
                    When satisfied that the paper meets Informing Science standards, the Editor will send it to the
                    Informing
                    Science
                    publisher, who will do the final formatting and quality control.

                    Articles appear online as soon as they are published.

