                    This
                    license does not permit you to use this material for commercial purposes.

                    <h3>Publication Fees</h3>

                    Developed Countries: 950 USD
                    Other Countries: 600 USD
                    African Countries : 300 USD

                    <h3>Ethical Considerations: Intellectual Property, Plagiarism, and Use of Human Participants.</h3>

                    When submitting a paper to a journal published by the Informing Science Institute, the author is
                    required to
                    assert
                    and confirm that the paper does not contain any copyrighted material except as noted in the paper
                    through proper
                    citation, that the paper is not currently under review by any other publication outlet, that once
                    the paper
                    enters
                    the review process for this journal the author will not submit the paper for publication
                    consideration to any
                    other
                    publication outlet, and that the paper contains no plagiarized material. Take care to give proper
                    attribution to
                    all
                    material from other sources since plagiarism is a serious academic offense. ISI journals conduct an
                    online
                    search of
                    submissions to uncover if the material provided has previously been published using iThenticate. The
                    full ethics
                    policy can be found here.

                    Authors are required to comply with all rules for human participants in research set forth by their
                    institution
                    and
                    applicable governmental agencies. We recommend that authors include in the body of the paper
                    relevant details
                    about
                    ethics or IRB approval for the use of human participants in their research. If IRB or ethics
                    approval is not
                    required, this may be stated in the body of the paper. Where reviewer or editor concerns are raised
                    in this
                    area,
                    authors are expected to provide documentation of this compliance. Authors are referred to the ISI
                    Ethics Policy
                    for
                    more details on the use of human participants in research.

                    <h3>Archiving</h3>

                    The journal's published articles are archived by Portico.

                    An author may choose to deposit all versions of their articles in an institutional or other
                    repository of the
                    author's choice without embargo.

                    <h3>Formatting</h3>

                    Papers that have been approved for publication after review must be formatted as nearly camera-ready
                    prior to
                    final
                    acceptance. We prefer that authors do their own formatting. However, for those with the budget and
                    without the
                    time,
                    for a fee of $250 we will hire a fellow ISI member on your behalf to do the routine formatting to
                    bring the
                    layout
                    into the standard format we use. Keep in mind that formatting is not the same as copy editing. The
                    formatter
                    does
                    not restructure or clarify your wording. We encourage those who are not familiar with writing in
                    journal English
                    to
                    take on a co-author or to hire their own copy editor competent to help with journal papers. Authors
                    are
                    encouraged
                    to make their own arrangements prior to submitting their paper. Some universities provide these
                    services for
                    their
                    researchers. ISI members can use the Peer Directory to locate ISI members interested in becoming
                    co-authors. If
                    your
                    paper is accepted pending final formatting, let your editor know if you wish to hire a formatter.
                    The editor
                    will
                    note this in the "paper's notes" and the publisher will have you pay the fee before hiring the
                    formatter.

                    <h3>Our 5 "C"s</h3>

                    Similar to the APA style manual guidelines (American Psychological Association, 2020, p. 376-377),
                    we seek to
                    publish papers that do the following:

                    - contribute significantly to the content area covered by the journal,
                    - communicate with clarity and conciseness, and
                    - conform to the journal’s style guidelines,
                    - communicates a clear and concise contribution that
                    - conforms to our style.

                    <h3>Check ISI Journals for Current Relevant Research</h3>

                    Be sure that your submission benefits from relevant current research by checking at
                    http://isjournals.org or
                    http://www.informingscience.org/Publications. Enter keywords for your research into the search box
                    to determine
                    if
                    there is current research that can strengthen your submission.

                    <h3>Peer Review Process - Timeframe for Review</h3>

                    Typically, within three weeks from when you submit your paper, the Editor-in-Chief Tian Luo and Dr
                    Kathryn
                    MacCallum
                    will conduct a desk review for suitability and the paper review system will contact the
                    corresponding author
                    with
                    news of whether or not the submission will be advanced to the first round of reviews (or is being
                    rejected as
                    not
                    suitable for publication in the journal). (If you do not hear from the Editor-in-Chief Tian Luo and
                    Dr Kathryn
                    MacCallum in a month, feel free to contact Tian Luo and Dr Kathryn MacCallum at tluo4work@gmail.com;
                    kathryn.maccallum@gmail.com.) Recognize that these suggested timeframes may be unattainable when the
                    Editor-in-Chief
                    has higher priority work constraints.

                    If the submission is desk accepted by the Editor-in-Chief for the first round of reviews, an Editor
                    and a panel
                    of
                    reviewers will be assigned to blind review the submission. This is a double-blind peer review in
                    which the
                    reviewers
                    do not know the submission author's identity and the author is never privy to the names of the
                    reviewers.

                    Typically the first round of review concludes approximately 6 weeks later with the Editor sending
                    the
                    corresponding
                    author a letter regarding acceptance. Whether or not the paper will be advanced for further review
                    or
                    publication,
                    at the conclusion of the review, the Editor provides the author with a development letter using the
                    input of the
                    reviewers. The decision may be to reject, conditionally accept pending specified revisions, or
                    accept the paper.
                    Most commonly papers that are accepted require several rounds of revision. Since the submission may
                    require
                    several
                    rounds of review and most of this time is determined by how promptly the author responds, there is
                    no meaningful
                    average time between submission and publication or rejection. While most rejections occur within one
                    week of
                    submission, submissions may be rejected at any point during the review cycle.

