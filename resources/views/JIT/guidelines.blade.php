                    Authors submit their manuscripts electronically using the submission and review system. All
                    manuscripts must be
                    the
                    authors' original, unpublished work. The manuscript must not be under consideration for publication
                    elsewhere.

                    We check all submissions for plagiarism using iThenticate. Please see our Ethics policy; we take
                    plagiarism
                    seriously.

