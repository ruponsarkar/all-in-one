                    <h4>Author information (added after paper has been accepted)</h4>

                    Once the Editor has accepted your paper, insert the full name, the affiliation (University or
                    Company), City,
                    Country, and email address for each author on the first page. Insert additional rows if there are
                    more than two
                    authors.

                    In the Author section at the end of the paper, add a short biography and a head-and-shoulders photo
                    (if
                    available)
                    for each author.

                    <h4>What to put in the abstract</h4>

                    The abstract is a brief summary of the contents of the article; it should give enough information to
                    make the
                    reader
                    want to learn more about your research. But it needs to be concise. In each of the boxes on the
                    first page,
                    enter
                    one or two brief sentences appropriate for your paper. Omit citations from the abstract; citations
                    for the
                    paper’s
                    sources do appear in the body of the paper.

                    If any of the abstract subtopics do not apply to your paper, put NA in that box.

                    <h4>Body of Paper</h4>

                    <strong>Introduction or background</strong>

                    All papers should begin with an introduction that sets the stage for the discussion. For some
                    disciplines, it
                    more
                    appropriate to use Background as an alternative first section.

                    <strong>Body</strong>

                    The body is a collection of multiple sections describing the main content of the paper. You should
                    use up to
                    three
                    levels of headings to categorize content as deemed necessary: Heading 1, Heading 2, and Heading 3.

                    <strong>Conclusion</strong>

                    This section summarizes the paper, presents challenges, suggests future study, and so on to create a
                    lasting
                    impression of the paper.

                    <strong>Appendix</strong>

                    If there is an appendix, place it after the References and before the Author information. If there
                    is more than
                    one
                    appendix, add a letter after “Appendix.”

                    If you have used a questionnaire in a study, include a copy of it as an appendix.

                    <strong>References</strong>

                    Following the conclusion is a list of all references used in the body of the paper. The current APA
                    formatting
                    guidelines are used to make internal citations within the body as well as provide the complete
                    alphabetic list
                    of
                    reference citations at the end of the paper. (See the Entering References section for more details.)
                    The
                    References
                    list contains only works cited in the paper and all works cited in the paper must be listed in the
                    References
                    section.

                    <strong>Author Information with Picture</strong>

                    After the paper is accepted, for each author of the paper, please provide a one or two paragraphs
                    that describe
                    the
                    author’s background relevant to this article. If you have one, insert a head-and-shoulder photo to
                    the left of
                    the
                    paragraphs about each author or send it separately and we will insert it.

                    <h3>Page Formatting</h3>

                    To make it easier to read the paper online, use single column formatting for the paper.

                    <strong>Page Size</strong>

                    Set the paper size to Letter, which is 8 1/2 by 11 inches.

                    <strong>Margins</strong>

                    Set the top and bottom margins to 1 inch and the right and left margins to 1.25 inches.

                    <strong>Headers and Footers</strong>

                    Insert page numbers in the footer. We will add the remaining information for the headers and
                    footers.

                    <strong>Hyphenation</strong>

                    Hyphenate the text in the document. To turn on hyphenation:

                    - Select Language on the Layout or Page Layout menu.
                    - Select Hyphenation.
                    - Check Automatically hyphenate document.

                    <strong>Footnotes</strong>

                    The journal does not allow for footnotes or endnotes. Insert your clarifications within the body of
                    the paper.
                    The
                    editors will remove most footnotes and place the material within the text.

