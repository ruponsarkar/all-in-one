                                Policy used by the ACM, an association for which we have much respect.</p>

                            <p>The Informing Science Institute ("ISI," "we," "us," or "our") is committed to protecting the privacy of its
                                members and other individuals with whom it interacts.</p>

                            <p>This Privacy Policy ("Policy") explains how we use and maintain the privacy of personal information we
                                collect online in connection with the ISI.org web site (the "Web Site"). For the purposes of any applicable
                                data protection laws (including the EU General Data Protection Regulation), the data controller in relation
                                to your personal information is the Informing Science Institute, with headquarters currently at 131
                                Brookhill Court, Santa Rosa, California 95409 USA.</p>

                            <p>This Policy will apply to personal information ISI collects or otherwise receives about third parties
                                ("you"), including ISI members ("Members"), when you use our Web Site or otherwise engage with us. Personal
                                information which is provided to us, or otherwise obtained by us, from which you can be identified
                                ("Personal Information") will only be used in the manner set out in this Policy. By visiting and/or
                                contacting us through the Web Site (or otherwise engaging with us), you need to be aware that we may
                                collect, use and transfer your Personal Information in the manner described in this Policy.</p>

